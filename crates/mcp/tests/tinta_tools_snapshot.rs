//! MCP tool names are what agents' permission manifests name (tintaoffice-web#33): a tool added,
//! renamed or removed, or its read-only hint changed, fails here until `docs/tinta-mcp-tools.tsv`
//! is regenerated on purpose (`TINTA_UPDATE_SNAPSHOT=1 cargo test -p wordcraft-mcp --test tinta_tools_snapshot`)
//! and the change noted in the release notes.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

const SNAPSHOT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/tinta-mcp-tools.tsv");

fn snapshot() -> String {
    let defs = wordcraft_mcp::tools::tool_definitions().as_array().cloned().unwrap_or_default();
    let mut lines: Vec<String> = defs
        .iter()
        .map(|t| {
            let name = t["name"].as_str().unwrap_or_default();
            let ro = t["annotations"]["readOnlyHint"].as_bool().unwrap_or(false);
            format!("{name}\t{}", if ro { "read_only" } else { "" })
        })
        .collect();
    lines.sort();
    let mut out = String::from("# Tinta Texto MCP tools (wordcraft-cli mcp). Generated by crates/mcp/tests/tinta_tools_snapshot.rs\n");
    for line in lines {
        out.push_str(&line);
        out.push('\n');
    }
    out
}

#[test]
fn mcp_tool_names_match_the_snapshot() {
    let now = snapshot();
    if std::env::var_os("TINTA_UPDATE_SNAPSHOT").is_some() {
        std::fs::write(SNAPSHOT, &now).unwrap();
        return;
    }
    let saved = std::fs::read_to_string(SNAPSHOT).unwrap_or_default();
    let old: std::collections::BTreeSet<&str> = saved.lines().collect();
    let new: std::collections::BTreeSet<&str> = now.lines().collect();
    let gone: Vec<&&str> = old.difference(&new).collect();
    let added: Vec<&&str> = new.difference(&old).collect();
    assert!(
        gone.is_empty() && added.is_empty(),
        "the MCP tools changed: gone {gone:?}, new {added:?}. Regenerate with \
         TINTA_UPDATE_SNAPSHOT=1 cargo test -p wordcraft-mcp --test tinta_tools_snapshot"
    );
}
